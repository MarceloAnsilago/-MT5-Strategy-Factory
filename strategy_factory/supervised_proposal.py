"""Proposal only, with frozen original candidates and no selected future dates."""
from copy import deepcopy
from dataclasses import asdict
from pathlib import Path
import re

from .analysis import read_artifact
from .batch_manifest import exact,fingerprint,sha,identifier
from .batch_safety import SETTINGS,STAGES
from .generator import verify_candidate,validate_spec,digest
from .integration_policy import ResourcePolicy

STOPS=('unknown_start','transport_failure','tester_busy','remote_or_cloud_agent','identity_mismatch',
       'timeout','resource_exceeded','audit_invalid','readiness_incompatible_or_unknown')


def validate_proposal(document):
    exact(document,{'schema_version','proposal_id','proposal_only','live_execution_enabled',
          'new_individual_authorizations_required','reuse_old_attempts','periods','resources',
          'stop_conditions','scenarios'},'supervised proposal')
    if (document['schema_version']!='3.3C-proposal-1' or document['proposal_only'] is not True or
        document['live_execution_enabled'] is not False or document['new_individual_authorizations_required'] is not True or
        document['reuse_old_attempts'] is not False):raise ValueError('non-executable proposal only')
    identifier(document['proposal_id'])
    if document['periods']!={s:None for s in STAGES} or document['stop_conditions']!=list(STOPS):
        raise ValueError('period selection and all stop conditions remain pending/required')
    ResourcePolicy(**document['resources'])
    scenarios=document['scenarios']
    if not isinstance(scenarios,list) or not scenarios or len(scenarios)>3:raise ValueError('one to three candidate proposals required')
    seen=set();seen_ids=set()
    for scenario in scenarios:
        exact(scenario,{'scenario_id','candidate_id','strategy_version','source_sha256','compiled_sha256',
              'spec_sha256','spec','inputs','parameters','tester_settings','max_attempts','scenario_sha256'},'proposal scenario')
        identifier(scenario['scenario_id']);identifier(scenario['candidate_id'])
        for k in ('source_sha256','compiled_sha256','spec_sha256','scenario_sha256'):
            sha(scenario[k])
            if scenario[k] is None:raise ValueError('proposal identity hash missing')
        spec=validate_spec(scenario['spec'])
        if (digest(spec)!=scenario['spec_sha256'] or scenario['candidate_id']!='g1_'+scenario['spec_sha256'][:16] or
            not isinstance(scenario['strategy_version'],str) or not re.fullmatch(r'\d+\.\d+',scenario['strategy_version']) or
            scenario['inputs']!={} or type(scenario['max_attempts']) is not int or scenario['max_attempts']!=1 or
            fingerprint(scenario['tester_settings'])!=fingerprint(SETTINGS)):
            raise ValueError('candidate/parameter policy mismatch')
        expected=dict(symbol=spec['symbol'],timeframe=spec['timeframe'],from_date=None,to_date=None,
                      deposit=10000,currency='BRL',leverage=1,model='every tick',execution_delay=0)
        if fingerprint(scenario['parameters'])!=fingerprint(expected):raise ValueError('original proposed settings changed')
        checksum=fingerprint({k:v for k,v in scenario.items() if k!='scenario_sha256'})
        if checksum!=scenario['scenario_sha256'] or scenario['candidate_id'] in seen or scenario['scenario_id'] in seen_ids:
            raise ValueError('duplicate or altered scenario')
        seen.add(scenario['candidate_id'])
        seen_ids.add(scenario['scenario_id'])
    return deepcopy(document)


def propose_supervised_batch(candidate_directories,compiled_hashes):
    """Verify existing generated bytes without generating, compiling or reserving."""
    scenarios=[]
    for directory in candidate_directories:
        directory=Path(directory);metadata=verify_candidate(directory)
        source=(directory/metadata['source_file']).read_text(encoding='utf-8')
        version=re.search(r'#property version\s+"([^"]+)"',source)
        if version is None:raise ValueError('strategy version absent')
        spec=validate_spec(read_artifact(directory/'spec.json'))
        scenario=dict(scenario_id='proposal-'+metadata['candidate_id'],candidate_id=metadata['candidate_id'],
            strategy_version=version[1],source_sha256=metadata['source_sha256'],
            compiled_sha256=compiled_hashes[metadata['candidate_id']],spec_sha256=metadata['spec_sha256'],spec=spec,
            inputs=metadata['manifest_inputs'],parameters=dict(symbol=spec['symbol'],timeframe=spec['timeframe'],
            from_date=None,to_date=None,deposit=10000,currency='BRL',leverage=1,model='every tick',execution_delay=0),
            tester_settings=deepcopy(SETTINGS),max_attempts=1)
        scenario['scenario_sha256']=fingerprint(scenario);scenarios.append(scenario)
    return validate_proposal(dict(schema_version='3.3C-proposal-1',proposal_id='phase33c-supervised-proposal-v1',
        proposal_only=True,live_execution_enabled=False,new_individual_authorizations_required=True,reuse_old_attempts=False,
        periods={s:None for s in STAGES},resources=asdict(ResourcePolicy(timeout_batch_seconds=900)),
        stop_conditions=list(STOPS),scenarios=scenarios))
